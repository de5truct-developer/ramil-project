heading2('1.4 Математические основы нечеткой логики и алгоритмов сравнения строк')

body('Интеллектуальный ассистент TechShop основан на концепции нечеткого поиска. В отличие от стандартного поиска, где строки «iPhone 15» и «айфон 15» считаются совершенно разными, нечеткий поиск позволяет находить соответствия с определенной долей вероятности.')

body('Фундаментальным алгоритмом, используемым в проекте, является расстояние Левенштейна, также называемое редакционным расстоянием. Это минимальное число элементарных операций, необходимых для превращения одной строки в другую. К элементарным операциям относятся: вставка одного символа, удаление одного символа и замена одного символа на другой.')

body('Расстояние Левенштейна d(a, b) между строками a и b вычисляется рекурсивно по следующей формуле:')

formula('d(i,j) = min(d(i-1,j)+1, d(i,j-1)+1, d(i-1,j-1)+c)', 2)
body('где d(i,j) — расстояние между первыми i символами строки a и первыми j символами строки b;')
body('c — стоимость замены, равная 0 при совпадении символов и 1 при различии.')

body('Например, для преобразования слова «кот» в «код» требуется одна операция замены символа «т» на «д», следовательно расстояние Левенштейна равно 1. Для преобразования «samsung» в «самсунг» потребуется несколько операций, но алгоритм вычисляет это автоматически, возвращая числовую меру различия двух строк.')

body('На основе расстояния Левенштейна вычисляется коэффициент подобия двух строк по формуле:')

formula('S(a,b) = (1 - d(a,b) / max(|a|, |b|)) * 100%', 3)
body('где S(a,b) — коэффициент подобия строк, процент;')
body('d(a,b) — расстояние Левенштейна;')
body('|a|, |b| — длины сравниваемых строк.')

body('В проекте для реализации данных алгоритмов используется библиотека FuzzyWuzzy, которая построена поверх модуля python-Levenshtein и предоставляет несколько усовершенствованных методов сравнения.')

body('Метод Simple Ratio вычисляет базовое расстояние Левенштейна между двумя строками и возвращает процент совпадения. Данный метод подходит для сравнения строк примерно одинаковой длины.')

body('Метод Partial Ratio выполняет сравнение короткой строки со всеми подстроками такой же длины в длинной строке и возвращает максимальное значение. Если одна строка является подстрокой другой, метод вернет высокий процент совпадения. Это особенно удобно для поиска категории, когда пользователь вводит сокращенное название.')

body('Метод Token Sort Ratio предварительно разбивает обе строки на отдельные слова, переводит их в нижний регистр, удаляет знаки препинания, сортирует слова в алфавитном порядке и только после этого вычисляет степень совпадения. Это позволяет обрабатывать запросы с произвольным порядком слов как идентичные.')

body('Метод Token Set Ratio выделяет общие слова в двух строках и сравнивает только их, позволяя игнорировать лишние слова в запросе пользователя. Данный метод является наиболее устойчивым к «шуму» в пользовательских запросах и используется в проекте как основной.')

body('Нечеткая логика расширяет классическую теорию множеств. Если в классической логике элемент либо принадлежит множеству, либо нет, то в нечеткой логике вводится функция принадлежности, определяемая по формуле:')

formula('mu(x) -> [0, 1]', 4)
body('где mu(x) — степень принадлежности элемента x к нечеткому множеству, принимающая значения в интервале от 0 до 1.')

body('В ассистенте TechShop данный принцип используется для принятия решений о релевантности результата поиска. Если коэффициент подобия превышает 90 процентов, ответ считается абсолютно верным. Если коэффициент находится в диапазоне от 70 до 90 процентов, система предлагает несколько вариантов на выбор. Если коэффициент ниже 50 процентов, запрос считается непонятым и система просит пользователя уточнить формулировку. Такой подход позволяет создать гибкую систему взаимодействия, которая прощает пользователю ошибки и понимает естественную речь.')


